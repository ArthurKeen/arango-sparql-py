"""The committed OWL mapping fixtures, one per layout (plan WP-LDBC-CORPUS).

The fixtures in ``mappings/ldbc_<layout>.ttl`` are the contract between the
loader and the translator. They are generated from :mod:`tests.ldbc.vocab`
(``python -m tests.ldbc.mappings --write``) and a test fails if a committed
file drifts from the generator.

``snvoc:directKnows`` maps onto the ``knows`` edges as an
``owl:SymmetricProperty`` (plan D10), traversed in both directions.
Relationships whose targets are all one class declare ``rdfs:range``, so a
constant object can be looked up and the edge walked backwards from it; every
predicate declares the ``rdfs:domain`` measured on the data
(``vocab.DOMAINS``), so a subject no type pattern names can be routed.

What the translator cannot map yet must **fail closed** (plan §5.2): in PG
and LPG, the reified relationships (plan D8) and the links out of a
relationship node are declared ``owl:ObjectProperty`` with no edge
collection, so a query that uses them raises ``SchemaResolutionError``.
Leaving them undeclared would be worse: the resolver reads an undeclared
predicate as a document attribute that does not exist, which returns no
rows instead of an error.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from rdflib import Graph

from arango_sparql.translate.resolver import SchemaResolver
from tests.ldbc import vocab
from tests.ldbc.loader import LPG_EDGES, LPG_NODES, RPT_COLLECTION, Layout

MAPPINGS_DIR = Path(__file__).parent / "mappings"

_HEADER = """\
# Generated by `python -m tests.ldbc.mappings --write` from tests/ldbc/vocab.py.
# Do not edit by hand; tests/ldbc/test_mappings.py fails if this file drifts.
# Layout: {layout}. See docs/architecture/ldbc_benchmark_plan.md §5.4.
@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix phys: <https://arango.solutions/phys#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .

"""

#: Predicates PG and LPG cannot map yet (plan D8): they must fail closed.
_UNMAPPED_IN_PG_LPG: tuple[str, ...] = tuple(
    sorted({r.entry for r in vocab.REIFIED} | {exit_ for r in vocab.REIFIED for exit_ in r.exits})
)

#: Attributes of reified relationship nodes (``joinDate``, ``classYear``,
#: ``workFrom``); ``creationDate`` is also a node attribute.
_RELATIONSHIP_ATTRIBUTES: tuple[str, ...] = tuple(
    sorted({a for r in vocab.REIFIED for a in r.attributes} - set(vocab.DATATYPE_PROPERTIES))
)


def _domain(iri: str) -> str:
    """`` ; rdfs:domain …`` for a predicate with a measured domain, else ``""``."""
    names = vocab.DOMAINS.get(iri)
    if not names:
        return ""
    classes = [f"<{vocab.CLASS_BY_NAME[n].iri}>" for n in names]
    if len(classes) == 1:
        return f" ; rdfs:domain {classes[0]}"
    return f" ; rdfs:domain [ owl:unionOf ( {' '.join(classes)} ) ]"


def _datatype_properties(layout: Layout) -> list[str]:
    # The RDF layout needs no domains: in a pure triple store every subject
    # reads the triples table (SchemaResolver.triple_store_class).
    return [
        f"<{iri}> a owl:DatatypeProperty{'' if layout == 'rpt' else _domain(iri)} ."
        for iri in (*vocab.DATATYPE_PROPERTIES, *_RELATIONSHIP_ATTRIBUTES)
    ]


def _plain_relationships() -> list[vocab.Relationship]:
    # rdf:type is the translator's class test, never an edge it traverses;
    # tag → tag-class typing (HAS_TYPE) is reachable only as data.
    return [r for r in vocab.RELATIONSHIPS if r.iri != vocab.RDF_TYPE]


def render(layout: Layout) -> str:
    lines: list[str] = []
    for cls in vocab.NODE_CLASSES:
        if layout == "rpt":
            lines.append(
                f'<{cls.iri}> a owl:Class ; phys:mappingStyle "RPT" ; '
                f'phys:triplesCollection "{RPT_COLLECTION}" .'
            )
        elif layout == "lpg":
            lines.append(
                f'<{cls.iri}> a owl:Class ; phys:collectionName "{LPG_NODES}" ; phys:mappingStyle "LABEL" ; '
                f'phys:typeField "labels" ; phys:typeFieldIsArray "true" ; phys:typeValue "{cls.name}" .'
            )
        else:
            lines.append(
                f'<{cls.iri}> a owl:Class ; phys:collectionName "{cls.pg_collection}" ; '
                'phys:mappingStyle "COLLECTION" .'
            )
    lines.append("")
    lines.extend(_datatype_properties(layout))
    lines.append("")
    if layout == "rpt":
        object_properties = sorted(
            {r.iri for r in _plain_relationships()} | set(_UNMAPPED_IN_PG_LPG) | {vocab.DIRECT_KNOWS}
        )
        lines.extend(
            f'<{iri}> a owl:ObjectProperty ; phys:mappingStyle "RPT_EDGE" .' for iri in object_properties
        )
    else:
        for rel in [*_plain_relationships(), vocab.DIRECT_KNOWS_EDGE]:
            kinds = "owl:ObjectProperty"
            if rel.iri == vocab.DIRECT_KNOWS:
                kinds += ", owl:SymmetricProperty"
            range_ = f" ; rdfs:range <{vocab.CLASS_BY_NAME[rel.range].iri}>" if rel.range else ""
            range_ += _domain(rel.iri)
            if layout == "lpg":
                lines.append(
                    f'<{rel.iri}> a {kinds} ; phys:edgeCollectionName "{LPG_EDGES}" ; '
                    f'phys:mappingStyle "GENERIC_WITH_TYPE" ; phys:typeField "type" ; '
                    f'phys:typeValue "{rel.name}"{range_} .'
                )
            else:
                lines.append(
                    f'<{rel.iri}> a {kinds} ; phys:edgeCollectionName "{rel.pg_collection}" ; '
                    f'phys:mappingStyle "DEDICATED_COLLECTION"{range_} .'
                )
        lines.append("# Not mappable yet (plan D8): declared with no edge collection so they fail closed.")
        lines.extend(f"<{iri}> a owl:ObjectProperty ." for iri in _UNMAPPED_IN_PG_LPG)
    return _HEADER.format(layout=layout) + "\n".join(lines) + "\n"


def path(layout: Layout) -> Path:
    return MAPPINGS_DIR / f"ldbc_{layout}.ttl"


def resolver(layout: Layout) -> SchemaResolver:
    """The resolver the harness translates with, configured as the live service is.

    ``strict_subject_resolution`` as in ``service.mapping``: an unroutable
    subject raises instead of scanning a ``Document`` collection that does
    not exist. ``fan_out_list_values`` for PG and LPG: they store
    multi-valued properties (``speaks``, ``email``) as arrays, and SPARQL
    sees one triple per value.
    """
    graph = Graph()
    graph.parse(data=path(layout).read_text(), format="turtle")
    return SchemaResolver(
        ontology=graph,
        strict_subject_resolution=True,
        fan_out_list_values=layout != "rpt",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    for layout in ("rpt", "lpg", "pg"):
        text = render(layout)  # type: ignore[arg-type]
        if args.write:
            MAPPINGS_DIR.mkdir(exist_ok=True)
            path(layout).write_text(text)  # type: ignore[arg-type]
        else:
            sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
